using System.Text;
using ClangSharp;
using ClangType = ClangSharp.Type;

namespace MetadataGenerator;

internal sealed class ComInterfaceGenerator(ComInterfaceGeneratorConfiguration configuration)
{
	private static readonly HashSet<string> CSharpKeywords =
	[
		"base", "bool", "byte", "char", "class", "decimal", "delegate", "double", "event",
		"explicit", "extern", "false", "fixed", "float", "implicit", "in", "int", "interface",
		"internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator",
		"out", "override", "params", "private", "protected", "public", "readonly", "ref",
		"return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
		"struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
		"unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
	];
	private static readonly HashSet<string> InputPointerTypedefs = ["PCCOR_SIGNATURE"];
	private static readonly HashSet<string> OutputWideStringOverrides =
	[
		"IMetaDataImport.GetEventProps.szEvent",
		"IMetaDataImport.GetPropertyProps.szProperty",
	];
	private static readonly Dictionary<string, string> ParameterTypeOverrides = new(StringComparer.Ordinal)
	{
		["IMetaDataImport.GetTypeDefProps.pdwTypeDefFlags"] = "CorTypeAttr",
		["IMetaDataImport.GetMethodProps.pdwAttr"] = "CorMethodAttr",
		["IMetaDataImport.GetEventProps.pdwEventFlags"] = "CorEventAttr",
		["IMetaDataImport.GetFieldProps.pdwAttr"] = "CorFieldAttr",
		["IMetaDataImport.GetMemberProps.pdwCPlusTypeFlag"] = "CorElementType",
		["IMetaDataImport.GetFieldProps.pdwCPlusTypeFlag"] = "CorElementType",
		["IMetaDataImport.GetPropertyProps.pdwCPlusTypeFlag"] = "CorElementType",
		["IMetaDataImport.GetParamProps.pdwCPlusTypeFlag"] = "CorElementType",
		["IMetaDataImport.GetPropertyProps.pdwPropFlags"] = "CorPropertyAttr",
		["IMetaDataImport.GetParamProps.pdwAttr"] = "CorParamAttr",
		["IMetaDataImport2.GetGenericParamProps.pdwParamFlags"] = "CorGenericParamAttr",
		["IMetaDataAssemblyImport.GetAssemblyProps.pdwAssemblyFlags"] = "CorAssemblyFlags",
		["IMetaDataAssemblyImport.GetAssemblyRefProps.pdwAssemblyRefFlags"] = "CorAssemblyFlags",
		["IMetaDataAssemblyImport.GetFileProps.pdwFileFlags"] = "CorFileFlags",
		["IMetaDataAssemblyImport.GetExportedTypeProps.pdwExportedTypeFlags"] = "CorTypeAttr",
		["IMetaDataAssemblyImport.GetManifestResourceProps.pdwResourceFlags"] = "CorManifestResourceFlags",
	};

	private readonly ComInterfaceTypeMapper _typeMapper = new();

	public void GenerateBindings(TranslationUnit translationUnit)
	{
		var records = Descendants(translationUnit.TranslationUnitDecl)
			.OfType<CXXRecordDecl>()
			.Where(record => record.HasDefinition && configuration.InterfaceMethodCounts.ContainsKey(record.Name))
			.GroupBy(record => record.Name, StringComparer.Ordinal)
			.ToDictionary(group => group.Key, group => group.Last().Definition!, StringComparer.Ordinal);

		foreach (var (name, expectedMethodCount) in configuration.InterfaceMethodCounts)
		{
			if (!records.TryGetValue(name, out var record))
				throw new InvalidOperationException($"Clang did not produce a definition for {name}.");
			if (!configuration.InterfaceGuids.TryGetValue(name, out var guid))
				throw new InvalidOperationException($"No IID was found for {name}.");

			var methods = record.Methods
				.Where(method => method.IsVirtual)
				.OrderBy(method => method.VtblIndex)
				.ToArray();
			if (methods.Length != expectedMethodCount)
				throw new InvalidOperationException($"{name} has {methods.Length} own virtual methods; expected {expectedMethodCount}.");
			var expectedVtblIndex = GetExpectedFirstVtblIndex(record);
			foreach (var method in methods)
			{
				if (method.VtblIndex != expectedVtblIndex)
					throw new InvalidOperationException($"{name}.{method.Name} has vtable index {method.VtblIndex}; expected {expectedVtblIndex}.");
				expectedVtblIndex++;
			}

			WriteIfChanged(Path.Combine(configuration.OutputDirectory, $"{name}.cs"), GenerateInterface(record, guid, methods));
		}
	}

	private static uint GetExpectedFirstVtblIndex(CXXRecordDecl record)
	{
		var index = 0u;
		for (var current = record; current.Bases.Count != 0;)
		{
			if (current.Bases.Count != 1 || current.Bases[0].Referenced is not CXXRecordDecl parent)
				throw new InvalidOperationException($"Cannot determine the primary COM base for {current.Name}.");
			index += (uint)parent.Methods.Count(method => method.IsVirtual);
			current = parent;
		}
		return index;
	}

	private string GenerateInterface(CXXRecordDecl record, Guid guid, IReadOnlyList<CXXMethodDecl> methods)
	{
		var parent = record.Bases.Count switch
		{
			0 => null,
			1 => record.Bases[0].Referenced.Name,
			_ => throw new InvalidOperationException($"{record.Name} has multiple native base classes."),
		};
		var inheritance = parent is null or "IUnknown" ? "" : $" : {parent}";
		var builder = new StringBuilder()
			.AppendLine("// <auto-generated />")
			.AppendLine("#nullable enable")
			.AppendLine("using System;")
			.AppendLine("using System.Reflection;")
			.AppendLine("using System.Runtime.InteropServices;")
			.AppendLine("using System.Runtime.InteropServices.Marshalling;")
			.AppendLine("using ICorDebugSharp;")
			.AppendLine()
			.Append("namespace ").Append(configuration.Namespace).AppendLine(";")
			.AppendLine()
			.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]")
			.AppendLine("[InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]")
			.Append("[Guid(\"").Append(guid.ToString("D").ToUpperInvariant()).AppendLine("\")]")
			.Append("public unsafe partial interface ").Append(record.Name).Append(inheritance).AppendLine()
			.AppendLine("{");

		for (var index = 0; index < methods.Count; index++)
		{
			var method = methods[index];
			builder.AppendLine("\t[PreserveSig]");
			if (GetTypedefName(method.ReturnType) == "BOOL")
				builder.AppendLine("\t[return: MarshalAs(UnmanagedType.Bool)]");
			builder.Append('\t').Append(MapReturnType(method.ReturnType)).Append(' ')
				.Append(EscapeIdentifier(method.Name)).Append('(');
			for (var parameterIndex = 0; parameterIndex < method.Parameters.Count; parameterIndex++)
			{
				if (parameterIndex != 0)
					builder.Append(", ");
				builder.Append(RenderParameter(record.Name, method, method.Parameters[parameterIndex], parameterIndex));
			}
			builder.AppendLine(");");
			if (index != methods.Count - 1)
				builder.AppendLine();
		}

		return builder.AppendLine("}").ToString();
	}

	private string MapReturnType(ClangType returnType) =>
		GetTypedefName(returnType) == "BOOL" ? "bool" : _typeMapper.Map(returnType);

	private string RenderParameter(string interfaceName, CXXMethodDecl method, ParmVarDecl parameter, int parameterIndex)
	{
		var typedefName = GetTypedefName(parameter.OriginalType);
		if (typedefName == "LPWSTR" || OutputWideStringOverrides.Contains($"{interfaceName}.{method.Name}.{parameter.Name}"))
		{
			var sizeParameterIndex = FindSizeParameterIndex(method, parameterIndex);
			return $"[Out][MarshalAs(UnmanagedType.LPArray, SizeParamIndex = {sizeParameterIndex})] char[]? {EscapeIdentifier(parameter.Name)}";
		}
		if (typedefName == "LPCWSTR")
			return $"[MarshalAs(UnmanagedType.LPWStr)] string {EscapeIdentifier(parameter.Name)}";

		if (ParameterTypeOverrides.TryGetValue($"{interfaceName}.{method.Name}.{parameter.Name}", out var parameterType))
		{
			var modifier = GetPointerType(parameter.Type) is null ? "" : "out ";
			return $"{modifier}{parameterType} {EscapeIdentifier(parameter.Name)}";
		}

		if (typedefName is not null && InputPointerTypedefs.Contains(typedefName))
			return $"{_typeMapper.Map(parameter.Type)} {EscapeIdentifier(parameter.Name)}";

		if (RequiresMaxOneMarshaller(method, parameterIndex))
			return $"[MarshalUsing(typeof(EnumeratorMax1Marshaller))] {_typeMapper.Map(parameter.Type)} {EscapeIdentifier(parameter.Name)}";

		if (GetArrayElementType(parameter.OriginalType) is { } elementType)
			return $"out {_typeMapper.Map(elementType)} {EscapeIdentifier(parameter.Name)}";

		if (GetReferenceType(parameter.Type) is { } reference)
			return $"ref {_typeMapper.Map(reference.PointeeType)} {EscapeIdentifier(parameter.Name)}";

		if (GetPointerType(parameter.Type) is { } pointer)
		{
			if (GetTypedefName(pointer.PointeeType) == "PCCOR_SIGNATURE")
			{
				var countParameterName = GetFollowingParameterName(method, parameterIndex, "signature byte count");
				return $"[MarshalUsing(CountElementName = nameof({EscapeIdentifier(countParameterName)}))] scoped out ReadOnlySpan<byte> {EscapeIdentifier(parameter.Name)}";
			}
			if (_typeMapper.Map(pointer.PointeeType) == "void")
				return $"{_typeMapper.Map(parameter.Type)} {EscapeIdentifier(parameter.Name)}";
			var modifier = GetTypedefName(pointer.PointeeType) == "HCORENUM" ? "ref" : "out";
			return $"{modifier} {_typeMapper.Map(pointer.PointeeType)} {EscapeIdentifier(parameter.Name)}";
		}

		return $"{_typeMapper.Map(parameter.Type)} {EscapeIdentifier(parameter.Name)}";
	}

	private static string GetFollowingParameterName(CXXMethodDecl method, int parameterIndex, string purpose)
	{
		var followingParameterIndex = parameterIndex + 1;
		if (followingParameterIndex >= method.Parameters.Count)
			throw new InvalidOperationException($"No {purpose} parameter follows {method.Name}.{method.Parameters[parameterIndex].Name}.");
		return method.Parameters[followingParameterIndex].Name;
	}

	private static ReferenceType? GetReferenceType(ClangType type)
	{
		while (true)
		{
			type = type switch
			{
				AttributedType attributed => attributed.ModifiedType,
				ElaboratedType elaborated => elaborated.NamedType,
				_ => type,
			};
			if (type is not AttributedType and not ElaboratedType)
				return type as ReferenceType;
		}
	}

	private static bool RequiresMaxOneMarshaller(CXXMethodDecl method, int parameterIndex) =>
		method.Parameters[parameterIndex].Name.Equals("cMax", StringComparison.OrdinalIgnoreCase) &&
		method.Parameters.Take(parameterIndex).Any(parameter => GetArrayElementType(parameter.OriginalType) is not null);

	private static ClangType? GetArrayElementType(ClangType type)
	{
		while (true)
		{
			type = type switch
			{
				AttributedType attributed => attributed.ModifiedType,
				ElaboratedType elaborated => elaborated.NamedType,
				AdjustedType adjusted => adjusted.OriginalType,
				_ => type,
			};
			if (type is not AttributedType and not ElaboratedType and not AdjustedType)
				return (type as ArrayType)?.ElementType;
		}
	}

	private static int FindSizeParameterIndex(CXXMethodDecl method, int bufferParameterIndex)
	{
		var sizeParameterIndex = bufferParameterIndex + 1;
		if (sizeParameterIndex >= method.Parameters.Count || GetPointerType(method.Parameters[sizeParameterIndex].Type) is not null)
			throw new InvalidOperationException($"No character count parameter follows {method.Name}.{method.Parameters[bufferParameterIndex].Name}.");
		return sizeParameterIndex;
	}

	private static PointerType? GetPointerType(ClangType type)
	{
		while (true)
		{
			type = type switch
			{
				AttributedType attributed => attributed.ModifiedType,
				ElaboratedType elaborated => elaborated.NamedType,
				AdjustedType adjusted => adjusted.GetAdjustedType,
				_ => type,
			};
			if (type is not AttributedType and not ElaboratedType and not AdjustedType)
				return type as PointerType;
		}
	}

	private static string? GetTypedefName(ClangType type)
	{
		while (true)
		{
			type = type switch
			{
				AttributedType attributed => attributed.ModifiedType,
				ElaboratedType elaborated => elaborated.NamedType,
				_ => type,
			};
			if (type is not AttributedType and not ElaboratedType)
				return (type as TypedefType)?.Decl.Name;
		}
	}

	private static IEnumerable<Decl> Descendants(Decl declaration)
	{
		foreach (var child in declaration.Decls)
		{
			yield return child;
			foreach (var descendant in Descendants(child))
				yield return descendant;
		}
	}

	private static string EscapeIdentifier(string name) => CSharpKeywords.Contains(name) ? $"@{name}" : name;

	private static void WriteIfChanged(string path, string content)
	{
		Directory.CreateDirectory(Path.GetDirectoryName(path)!);
		if (File.Exists(path) && File.ReadAllText(path) == content)
			return;
		File.WriteAllText(path, content.Replace("\r\n", "\n"));
	}
}
